/* faixa de informaÃ§Ãµes com rolagem infinita (via JS â€” ignora prefers-reduced-motion) */
(function marquee() {
  const box = document.getElementById("ribbon");
  const track = document.getElementById("ribbonTrack");
  if (!box || !track) return;

  const base = Array.from(track.children).map(el => el.outerHTML);
  const setHTML = base.join("");
  track.style.animation = "none";           // desliga a animaÃ§Ã£o CSS
  track.style.willChange = "transform";

  let oneSet = 0, offset = 0, last = 0, paused = false;
  const SPEED = 48;                          // px por segundo

  function build() {
    track.style.transform = "translate3d(0,0,0)";
    track.innerHTML = setHTML;               // mede um conjunto
    oneSet = track.scrollWidth;
    const need = Math.max(2, Math.ceil((box.clientWidth * 2) / (oneSet || 1)) + 1);
    let html = "";
    for (let i = 0; i < need; i++) html += setHTML;
    track.innerHTML = html;
    offset = offset % oneSet;
  }

  function frame(now) {
    if (!last) last = now;
    const dt = Math.min((now - last) / 1000, 0.05);   // evita salto ao voltar de outra aba
    last = now;
    if (!paused && oneSet > 0) {
      offset -= SPEED * dt;
      if (offset <= -oneSet) offset += oneSet;
      track.style.transform = `translate3d(${offset}px,0,0)`;
    }
    requestAnimationFrame(frame);
  }

  build();
  requestAnimationFrame(frame);
  window.addEventListener("resize", build);
  box.addEventListener("mouseenter", () => paused = true);
  box.addEventListener("mouseleave", () => paused = false);
  // nÃ£o deixa a faixa "acelerar" se o navegador ficar em background
  document.addEventListener("visibilitychange", () => { last = 0; });
})();

